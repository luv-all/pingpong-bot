use std::time::Duration;

use crate::Vector3;

/// 검출 자체의 픽셀 노이즈 σ [px].
///
/// 이것만으로 가중치를 정하면 안 된다 — 캘리브가 틀어진 만큼도 그 카메라의 픽셀은 못
/// 믿는다. [`crate::vision::fit::sigma_px`]가 둘을 합친다.
pub const SIGMA_PX: f64 = 1.5;
/// 이보다 크게 어긋난 관측은 창에서 뺀다 [σ 배수].
///
/// 로버스트 손실이 이미 무게를 줄이지만, 완전히 다른 것을 잡은 관측은 아예 빼야 한다.
pub const OUTLIER_SIGMA: f64 = 8.0;
/// 로버스트 손실이 선형으로 꺾이는 지점 [σ 배수].
pub const HUBER_SIGMA: f64 = 3.0;
/// 적합을 시작할 최소 관측 수. 미지수가 6개라 3개(6행)면 딱 맞고, 그건 너무 빠듯하다.
pub const MIN_SIGHTINGS: usize = 6;
/// 창에 들고 있을 시간. 이보다 오래된 관측은 다음 공일 수 있다.
pub const WINDOW: Duration = Duration::from_millis(1500);
/// 관측이 이만큼 끊기면 트랙을 버린다.
pub const STALE_GAP: Duration = Duration::from_millis(500);
/// 연속으로 이만큼 이탈하면 트랙을 끝낸다.
///
/// 세계가 모델과 안 맞기 시작했다는 뜻이다 — 라켓에 맞아 되돌아가거나, 다른 공이 들어왔거나.
/// 하나씩 빼기만 하면 되돌아온 공이 창에 조금씩 스며 적합을 망친다. 실측 fly_10 에서 한
/// 클립에 트랙이 6개 서고 잔차가 15.7 px 였다.
pub const OUTLIER_LIMIT: u32 = 3;
/// 샷으로 볼 최소 속력 [m/s]. 굴러다니거나 멈춘 공이 트랙을 붙들면 안 된다.
///
/// 클립에는 발사 전후로 공이 놓여 있는 구간이 길다 (실측 생 속력 0.05 m/s 구간).
pub const MIN_SPEED: f64 = 1.0;
/// 창 안의 관측이 이미지에서 이만큼은 움직여야 적합을 시도한다 [px].
///
/// 속력으로만 거르면 멈춘 공에도 트랙을 세웠다 바로 죽이길 반복한다 — 실측 fly_10 에서
/// 한 클립에 99번이었다. 화소 이동은 3D 를 풀기 **전에** 볼 수 있어서 그 헛수고를 막는다.
/// 4 m/s 공은 80 fps 에서 6프레임에 20 px 넘게 간다. 놓여 있는 공은 2 px 도 안 움직인다.
pub const MIN_PIXEL_SPAN: f64 = 12.0;
/// 적분 스텝과 예측 궤적 표본 간격.
pub const INTEGRATE_DT: Duration = Duration::from_millis(1);
pub const SAMPLE_DT: Duration = Duration::from_millis(5);
/// 예측 궤적 상한.
pub const HORIZON: Duration = Duration::from_secs(2);

/// 비전 예측 전용 e·μ·drag — [`crate::defaults::PhysicsParams::default`]와 **일부러
/// 다르다.**
///
/// `PhysicsParams::default()`의 `restitution=0.72`·`friction=0.4`는 `measure-restitution`
/// 창 회귀로 잰 **테이블·공 자체의** 물리값이고 sim(rapier)도 같이 쓴다 — 스핀과 무관한
/// 측정이라 정직하다. 여기 셋(`RESTITUTION`·`FRICTION`·`DRAG`)은 그게 아니다 —
/// `clip_review --calibrate`가 **`ω=0` 가정 상태의 예측 오차**를 최소화하도록 fly_45~53
/// 9클립에 좌표하강으로 공유 탐색한 값이다(2026-08-12). 라이브 스핀이 못 풀린 6/9
/// 클립에서 predicted가 계속 실제보다 멀리·높이 나가는 걸 이 셋이 같이 흡수한다 —
/// e=0.86이 참 반발계수(0.72)보다 뚜렷이 높은 게 그 증거다(빠진 스핀의 자리를 반발이
/// 대신 메움). **그래서 sim에는 안 올린다** — `PhysicsParams::default()`를 이 값으로
/// 바꾸면 sim의 진짜 반발 시뮬레이션까지 이 보정을 물려받는다. 예전에 `DRAG`만 이렇게
/// 따로 뒀던 것과 같은 이유(`Fit::new`의 TODO 참고)로 셋 다 여기로 옮긴다.
///
/// `clip_review --calibrate`(`src/defaults/control.rs`의 `min_swing_secs=0.20`이 로봇이
/// 실제로 쓰는 하한이라 0.2s 리드 타점 오차 중앙값을 점수로 씀) 결과, 기본값
/// (e=0.72,μ=0.4,drag=0.126) 대비 중앙값 5.24cm → **1.28cm**. 회귀 366+/9(기존 무관
/// 실패만) 그대로.
///
/// 스핀 라이브 발동률이 오르면 이 보정이 필요한 몫도 줄어야 정상이다 — 그때
/// `--calibrate`를 다시 돌려 재수렴시킬 것.
///
/// 2026-08-13에 그 시점이 와서(스핀 솔버 고쳐 0/9 → 2/9) 되돌려 봤다. 결과는
/// **셋을 갈라서 봐야 한다** (`clip-review --trigger-sweep`의 물리 비교표, 클립별
/// 접수 평면 오차 중앙값의 평균):
///
/// | 물리 | 평균 |
/// |---|---|
/// | 지금(보정) | 6.66cm |
/// | e만 참값(0.72) | 6.39cm |
/// | 전부 참값(0.72, 0.4, 0.126) | **16.08cm** |
///
/// `mu`·`drag`는 여전히 확실히 값을 한다 — 셋 다 되돌리면 fly_45가 3.5 → 35.4cm로
/// 터진다. `e`만 참값으로 두는 건 평균 0.27cm 나아지지만 클립별로 엇갈려서
/// (fly_51 −5.9, fly_49 +2.4) 산포 안쪽이고, 스핀도 2/9 → 1/9로 줄어든다
/// (fly_46의 롤 판정이 참 e에서 슬립으로 뒤집힌다). 근거가 모자라 안 바꿨다 —
/// 다시 물어보려면 클립을 더 찍고 나서다.
pub const RESTITUTION: f64 = 0.8617;
pub const FRICTION: f64 = 0.5;
pub const DRAG: f64 = 0.151;

/// 바운스에서 스핀을 못 풀었을 때만 쓰는 사전값 [rad/s].
///
/// 예전엔 210(슈터 전용, 클립 9개 ω_x 137~251·중앙값 210·부호 전부 같음)이었다 — 슈터가
/// 매번 같은 스핀을 먹이는 기계라 그때는 단일 상수가 통했다. 2026-08-12에 사람 서브
/// 9개(fly_45~53)를 같은 방식으로 재보니 -62~153으로 흩어졌고, 절반은 0 근처·절반은
/// 130대인 이봉 분포라 부호조차 안 정해진다(`spin_after_bounce_if_rolling`,
/// `src/physics/measure/spin_from_bounce.rs`) — 사람마다·서브마다 다른 게 당연하다.
/// 이 분포에서 절대오차를 최소화하는 한 점(중앙값 ≈14)도 0과 거의 차이가 없어서, 있지도
/// 않은 확신을 상수에 담느니 0(무회전 가정)으로 둔다.
///
/// **그래서 이 값은 이제 안전장치일 뿐, 대표값이 아니다.** 진짜 답은 매 샷 바운스에서
/// 라이브로 푸는 것(`vision::Fit::solve_spin_from_bounce`)이고, 그게 안 풀렸을 때만
/// 여기로 떨어진다. 발동 안 되면(현재 이 클립들에선 거의 그렇다) 이 0이 곧 "스핀 무시"인
/// 셈이라 원래 슈터만큼 좋을 수 없다 — 이건 라이브 발동률을 올려야 풀리는 문제지 이
/// 상수를 조정해서 풀 문제가 아니다.
///
/// ω_y·ω_z 는 여전히 0 — ω_z 는 바운스 접촉점 속도 `(v_x - Rω_y, v_y + Rω_x, 0)`에 아예
/// 안 들어가 관측 자체가 안 된다.
pub const ASSUMED_SPIN: Vector3 = Vector3::new(0.0, 0.0, 0.0);

/// 슈터가 공을 내보내는 가로 위치 [m]. 궤적 시작 x 의 사전값이다.
///
/// x 는 두 카메라가 다 테이블 +X 옆면이라 **가장 안 보이는 축**이다 (`diag_layout`:
/// σ_x 6 mm vs σ_y·σ_z 3~4 mm). 리그가 이미 아는 것을 넣어 주면 그만큼 관측을 아낀다.
///
/// 기하로는 `WIDTH_X / 2 = 0.763` 인데 실측은 클립 9개에서 평균 0.820, 표준편차 0.040 이다
/// (`diag_physics::does_the_ball_start_from_the_middle`). 5.7 cm 차이가 슈터가 실제로
/// 그만큼 옆에 있어서인지 캘리브가 x 로 밀려서인지는 아직 못 가른다 — 3 m 거리에서
/// 5.7 cm 는 17 px 이라 cam0 rmse 4.15 px 보다 크므로 슈터 쪽이 유력하다.
///
/// TODO(측정): 줄자로 슈터 사출구의 x 를 재면 바로 갈린다. 기하값과 맞으면 캘리브가
/// 밀린 것이고, 실측과 맞으면 그냥 슈터가 옆에 있는 것이다.
pub const SHOOTER_X: f64 = 0.820;
/// 그 사전값을 얼마나 믿나 [m]. 클립 9개의 표준편차다.
///
/// 하드 제약이 아니라 소프트다 — 관측이 충분하면 데이터가 이겨야 한다.
pub const SHOOTER_X_SIGMA: f64 = 0.040;
