/// [`Arm::inverse_pose_with_rail`](crate::robot::Arm::inverse_pose_with_rail)의 탐색 폭.
///
/// 팔 4축 + 레일 1축에 5차원 과제(위치 3 + 법선 2)라 **여유자유도가 없어** 해가 이산
/// 분기로 갈린다. 힌트 근처에서만 출발하면 다른 분기의 해를 못 보고 "해 없음"을 반환한다
/// (실측: FK가 만들어 해가 보장된 표적 256개 중 54.3%만 복원).
///
/// 전역 스윕이 그걸 100%로 올리지만 공짜가 아니다 — 도달범위 안인데 그 법선으로는 풀리지
/// 않는 표적에서 시드를 모두 태운다. 그래서 호출부가 **실패의 대가**에 따라 고른다.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IkSearch {
    /// 힌트와 레일 기반 시드만. 실패가 싸게 먹히는 고주파 best-effort 경로용 —
    /// coarse 추종은 매 물리 틱(1 kHz) 도는 rough 목표라 이번 틱에 못 풀면 다음 틱에
    /// 다시 시도하면 된다. 전역 스윕을 여기 두면 물리 스텝을 블로킹한다
    /// (실측: `bang_bang_swing_planning_does_not_block_physics_step`이 25.8 ms/step,
    /// 허용 20 ms).
    Local,
    /// 관절 한계를 고르게 덮는 저불일치 시드까지 스윕한다. **실패가 곧 기회 상실**인
    /// 경로용 — 스윙 커밋은 공 하나에 한 번뿐이라 여기서 못 찾으면 그 공은 끝이다.
    Global,
}
